export function isLegalKind(value: unknown): value is LegalKind {
  return value === "terms" || value === "privacy";
}

// 버전 문자열 비교 ("1.10" > "1.9")
export function compareVersions(a: string, b: string) {
  const pa = a.split(".").map(Number);
  const pb = b.split(".").map(Number);
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    const d = (pa[i] ?? 0) - (pb[i] ?? 0);
    if (d !== 0) return d;
  }
  return 0;
}

// 시행일이 지난 것 중 가장 최근 = 현재 버전, 시행일이 아직 안 온 것 = 예정 버전
export function splitVersions(docs: LegalDocument[], now = new Date()) {
  const sorted = [...docs].sort(
    (a, b) =>
      new Date(b.effective_at).getTime() - new Date(a.effective_at).getTime(),
  );
  const effective = sorted.filter((d) => new Date(d.effective_at) <= now);
  const scheduled = sorted.filter((d) => new Date(d.effective_at) > now);
  return { current: effective[0] ?? null, effective, scheduled };
}

